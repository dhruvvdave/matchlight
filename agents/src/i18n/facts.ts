/** Render a fact's evidence text in `lang` (falls back to the canonical English text). */
export function factText(f: Fact, lang: Language): string {
  if (lang === 'en' || !f.tkey) return f.text;
  const key = f.tkey.startsWith('after_') ? f.tkey : f.tkey;
  const tpl = T[lang][key];
  return tpl ? fill(tpl, f.params ?? {}) : f.text;
}
